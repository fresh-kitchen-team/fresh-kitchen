CREATE TABLE ingredient_catalog_alias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catalog_id BIGINT NOT NULL,
    alias_name VARCHAR(100) NOT NULL,
    normalized_alias_name VARCHAR(100) NOT NULL,
    language VARCHAR(10) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_ingredient_catalog_alias_name_not_blank
        CHECK (length(btrim(alias_name)) > 0),
    CONSTRAINT ck_ingredient_catalog_alias_normalized_name_not_blank
        CHECK (length(btrim(normalized_alias_name)) > 0),
    CONSTRAINT ck_ingredient_catalog_alias_language
        CHECK (language IN ('KO', 'EN')),
    CONSTRAINT fk_ingredient_catalog_alias_catalog
        FOREIGN KEY (catalog_id) REFERENCES ingredient_catalog(id) ON DELETE CASCADE,
    CONSTRAINT uk_ingredient_catalog_alias_normalized_name
        UNIQUE (normalized_alias_name)
);

